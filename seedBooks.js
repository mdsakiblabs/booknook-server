async function seedBooks() {
  const client = new MongoClient(MONGO_URI);

  try {
    await client.connect();

    console.log("Connected to MongoDB.");

    const db = client.db(DB_NAME);
    const collection = db.collection(COLLECTION_NAME);

    const booksToSeed = books.map((book, index) => ({
      ...book,
      image: `https://covers.openlibrary.org/b/isbn/${book.isbn}-L.jpg?default=false`,
      addedBy: "BookNook Editorial",
      addedByEmail: "seed@booknook.local",
      createdAt: new Date(Date.now() - (books.length - index) * 60000),
    }));

    const operations = booksToSeed.map((book) => ({
      updateOne: {
        filter: { isbn: book.isbn },
        update: { $setOnInsert: book },
        upsert: true,
      },
    }));

    const result = await collection.bulkWrite(operations);

    console.log("--------------------------------");
    console.log("BookNook seed completed!");
    console.log(`Total records in seed: ${books.length}`);
    console.log(`New books inserted: ${result.upsertedCount}`);
    console.log(`Already existed: ${result.matchedCount}`);
    console.log("--------------------------------");
  } catch (error) {
    console.error("Seed failed:", error);
  } finally {
    await client.close();
    console.log("MongoDB connection closed.");
  }
}

seedBooks();
